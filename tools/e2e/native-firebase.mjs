const root = resolve(dirname(fileURLToPath(import.meta.url)), '../..');
const projectId = 'demo-household-account-e2e';
const email = 'playwright@household.test';
const password = 'playwright-password-1234';
const output = join(root, 'web/test-results/native-firebase');
