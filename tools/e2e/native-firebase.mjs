function readLogSince(path, offset) {
  const descriptor = openSync(path, 'r');
  try {
    const length = fstatSync(descriptor).size - offset;
    assert(length >= 0, 'Firebase log was truncated during Native E2E');
    const buffer = Buffer.alloc(length);
    let consumed = 0;
    while (consumed < length) {
      const count = readSync(descriptor, buffer, consumed, length - consumed, offset + consumed);
      assert(count > 0, 'Firebase log ended before the observed size');
      consumed += count;
    }
    return buffer.toString('utf8');
  } finally { closeSync(descriptor); }
}

async function jsonRequest(url, options = {}) {
  const response = await fetch(url, { ...options, signal: AbortSignal.timeout(60_000) });
  const text = await response.text();
  assert(response.ok, `Local E2E request failed (${response.status}): ${text}`);
  return text ? JSON.parse(text) : {};
}

async function seed({ performance = false } = {}) {
  // Only the fixed demo project on loopback is reachable. Never accept a production project argument.
  await Promise.all([
    jsonRequest(`http://127.0.0.1:9099/emulator/v1/projects/${projectId}/accounts`, { method: 'DELETE' }),
    jsonRequest(`http://127.0.0.1:8080/emulator/v1/projects/${projectId}/databases/(default)/documents`, { method: 'DELETE' }),
  ]);
  const account = await jsonRequest('http://127.0.0.1:9099/identitytoolkit.googleapis.com/v1/accounts:signUp?key=demo-api-key', {
    method: 'POST', headers: { 'content-type': 'application/json' }, body: JSON.stringify({ email, password, returnSecureToken: true }),
  });
  async function command(name, payload, householdId, idToken = account.idToken) {
    const commandId = `native-e2e-${randomUUID()}`;
    const response = await jsonRequest(`http://127.0.0.1:5001/${projectId}/asia-northeast3/executeHouseholdCommand`, {
      method: 'POST', headers: { 'content-type': 'application/json', authorization: `Bearer ${idToken}` },
      body: JSON.stringify({ data: { contractVersion: 'household-command.v1', commandId, idempotencyKey: commandId,
        ...(householdId ? { householdId } : {}), command: name, payload } }),
    });
    assert.equal(response.result?.contractVersion, 'household-command-response.v1');
    assert.equal(response.result?.result.kind, 'succeeded', `${name}: ${JSON.stringify(response.result)}`);
    return response.result.result.value;
  }
  const household = await command('access.create-household-with-self.v1', { householdName: 'Native E2E', memberName: 'Native E2E' });
  let categoryName = '간식/디저트/커피';
  let categoryId;
  // The ID must be generated by the real server and contain both cases, to catch the original regression.
  for (let attempt = 0; attempt < 5; attempt++) {
    categoryName = `간식/디저트/커피${attempt ? ` ${attempt}` : ''}`;
    ({ categoryId } = await command('category.create.v1', { category: { label: categoryName, color: '#F9A8D4' } }, household.householdId));
    if (/[A-Z]/.test(categoryId) && /[a-z]/.test(categoryId)) break;
  }
  assert(/[A-Z]/.test(categoryId) && /[a-z]/.test(categoryId), 'Server-generated mixed-case category ID is required');
  await command('payment-configuration.register-card.v1', { card: { cardLabel: '국민', cardLastFour: '1234' } }, household.householdId);
  await command('payment-configuration.create-merchant-rule.v1', { rule: {
    merchantKeyword: 'E2E커피점', matchType: 'exact', mapping: { merchant: 'E2E 카페', category: categoryId },
  } }, household.householdId);
  const now = new Date();
  const seoul = new Date(now.getTime() + 9 * 60 * 60 * 1000).toISOString();
  const rawNotification = {
    contractVersion: 'android-raw-notification.v1', observationId: `native-e2e-${randomUUID()}`,
    packageName: 'com.kbcard.cxh.appcard',
    notification: { postedAt: now.toISOString(), title: 'KB국민카드1234 승인', textLines: [
      '12,300원 일시불', `${seoul.slice(5, 7)}/${seoul.slice(8, 10)} ${seoul.slice(11, 16)}`, 'E2E커피점',
    ] },
  };
  const fixture = { projectId, email, password, householdId: household.householdId, memberId: household.memberId,
    categoryId, categoryName, rawNotification, expectedMerchant: 'E2E 카페', expectedAmountInWon: 12300 };
  if (performance) {
    for (const [memberEmail, memberName] of [['native-partner@household.test', '성능 배우자'], ['native-child@household.test', '성능 아이']]) {
      const member = await jsonRequest('http://127.0.0.1:9099/identitytoolkit.googleapis.com/v1/accounts:signUp?key=demo-api-key', {
        method: 'POST', headers: { 'content-type': 'application/json' },
        body: JSON.stringify({ email: memberEmail, password, returnSecureToken: true }),
      });
      const invitation = await command('access.create-invitation.v1', {}, household.householdId);
      await command('access.join-household-as-self.v1', { invitationCode: invitation.invitationCode, memberName }, undefined, member.idToken);
    }
    const fields = object => Object.fromEntries(Object.entries(object).map(([key, value]) => [key,
      typeof value === 'number' ? { integerValue: String(value) } : { stringValue: value }]));
    const writes = [];
    const seoulYear = Number(seoul.slice(0, 4));
    const seoulMonth = Number(seoul.slice(5, 7)) - 1;
    for (let monthsAgo = 0; monthsAgo < 36; monthsAgo++) {
      for (let index = 0; index < 60; index++) {
        const date = new Date(Date.UTC(seoulYear, seoulMonth - monthsAgo, index % 28 + 1)).toISOString().slice(0, 10);
        writes.push({ update: {
          name: `projects/${projectId}/databases/(default)/documents/households/${household.householdId}/ledgerTransactions/native-performance-${monthsAgo}-${index}`,
          fields: fields({ householdId: household.householdId, merchant: `합성 거래 ${monthsAgo}-${index}`,
            amountInWon: 1000 + index * 100 + monthsAgo * 10, categoryId, accountingDate: date, localTime: '12:00',
            memo: '', transactionType: 'expense', lifecycleState: 'active', aggregateVersion: 1,
            creatorMemberId: household.memberId, cardType: 'manual', cardDisplay: '', source: 'manual', schemaVersion: 2 }),
        } });
      }
    }
    for (let offset = 0; offset < writes.length; offset += 400) {
      await jsonRequest(`http://127.0.0.1:8080/v1/projects/${projectId}/databases/(default)/documents:commit`, {
        method: 'POST', headers: { 'content-type': 'application/json', authorization: 'Bearer owner' },
        body: JSON.stringify({ writes: writes.slice(offset, offset + 400) }),
      });
    }
    fixture.performanceDataset = { members: 3, months: 36, expensesPerMonth: 60, expenses: writes.length };
    fixture.expectedMonthlyExpenseInWon = 237000;
    // Verify the real authenticated home query before building/launching Android or measuring time.
    // A stale fixture path/field must fail here, not after the UI waits for an impossible total.
    const month = seoul.slice(0, 7);
    const monthEnd = new Date(Date.UTC(seoulYear, seoulMonth + 1, 0)).toISOString().slice(0, 10);
    const result = await jsonRequest(`http://127.0.0.1:8080/v1/projects/${projectId}/databases/(default)/documents/households/${household.householdId}:runQuery`, {
      method: 'POST', headers: { 'content-type': 'application/json', authorization: `Bearer ${account.idToken}` },
      body: JSON.stringify({ structuredQuery: {
        from: [{ collectionId: 'ledgerTransactions' }],
        where: { compositeFilter: { op: 'AND', filters: [
          ['householdId', 'EQUAL', household.householdId],
          ['accountingDate', 'GREATER_THAN_OR_EQUAL', `${month}-01`],
          ['accountingDate', 'LESS_THAN_OR_EQUAL', monthEnd],
        ].map(([fieldPath, op, stringValue]) => ({ fieldFilter: { field: { fieldPath }, op, value: { stringValue } } })) } },
      } }),
    });
    const monthly = result.flatMap(row => row.document ? [row.document.fields] : []);
    assert.equal(monthly.length, 60, 'Authenticated home query must read all 60 fixture expenses');
    assert(monthly.every(row => row.categoryId?.stringValue === categoryId
      && row.transactionType?.stringValue === 'expense' && row.lifecycleState?.stringValue === 'active'),
    'Home fixture must contain visible expenses with the actual category');
    assert.equal(monthly.reduce((sum, row) => sum + Number(row.amountInWon?.integerValue), 0),
      fixture.expectedMonthlyExpenseInWon, 'Authenticated home fixture monthly amount must match');
    console.log(`Native performance fixture verified: ${monthly.length} monthly expenses / ${fixture.expectedMonthlyExpenseInWon} KRW`);
  }
  mkdirSync(output, { recursive: true });
  writeFileSync(fixturePath, JSON.stringify(fixture), 'utf8');
  console.log(`Native Firebase E2E fixture prepared: ${fixturePath}`);
  return fixture;
}

async function run(command, args, cwd = root, env = process.env) {
  await new Promise((resolveRun, reject) => {
    const child = spawn(command, args, { cwd, env, stdio: 'inherit', windowsHide: true, shell: process.platform === 'win32' && /\.(?:bat|cmd)$/.test(command) });
    child.once('error', reject);
    child.once('exit', code => code === 0 ? resolveRun() : reject(new Error(`${command} failed (${code})`)));
  });
}

const mode = process.argv[2] ?? 'run';
assert(['run', 'seed', 'seed-performance', 'verify', 'performance', 'performance-isolated'].includes(mode),
  'Usage: node tools/e2e/native-firebase.mjs [run|seed|seed-performance|verify|performance|performance-isolated]');
const performanceMode = ['performance', 'performance-isolated', 'seed-performance'].includes(mode);
const isolateWebView = mode === 'performance-isolated';
const performanceSamples = Number(process.env.PERFORMANCE_SAMPLES ?? 7);
if (performanceMode) assert(Number.isInteger(performanceSamples) && performanceSamples >= 1 && performanceSamples <= 30,
  'PERFORMANCE_SAMPLES must be an integer from 1 to 30');
if (mode === 'seed' || mode === 'seed-performance') await seed({ performance: performanceMode });
else {
  const adb = process.env.ANDROID_HOME || process.env.ANDROID_SDK_ROOT
    ? join(process.env.ANDROID_HOME ?? process.env.ANDROID_SDK_ROOT, 'platform-tools', process.platform === 'win32' ? 'adb.exe' : 'adb') : 'adb';
  let webRuntime;
  const firebaseLog = join(root, 'firebase-debug.log');
  let logOffset = 0;
  try {
  if (mode === 'run' || performanceMode) {
    const fixture = await seed({ performance: performanceMode });
    webRuntime = await startNativeWebRuntime(root, output, adb);
    logOffset = existsSync(firebaseLog) ? statSync(firebaseLog).size : 0;
    await run(process.platform === 'win32' ? 'gradlew.bat' : './gradlew', [
      'connectedDebugAndroidTest', '-PfirebaseE2e=true', '-PfirebaseWebE2e=true',
      // AGP normally uninstalls both APKs before Gradle returns, deleting private result files.
      // Its supported stable option preserves the E2E installation for the reads below.
      '-Pandroid.injected.androidTest.leaveApksInstalledAfterRun=true',
      `-PWEB_APP_URL=${webRuntime.origin}/`, '-PWEB_ENVIRONMENT_VERSION=emulator-e2e-v1',
      `-Pandroid.testInstrumentationRunnerArguments.webOrigin=${webRuntime.origin}`,
      ...(performanceMode ? [
        '-Pandroid.testInstrumentationRunnerArguments.class=com.household.account.e2e.NativePerformanceFirebaseE2ETest',
        `-Pandroid.testInstrumentationRunnerArguments.performanceSamples=${performanceSamples}`,
        `-Pandroid.testInstrumentationRunnerArguments.performanceIsolateWebView=${isolateWebView}`,
      ] : ['-Pandroid.testInstrumentationRunnerArguments.notAnnotation=com.household.account.e2e.FirebasePerformanceE2E']),
      `-Pandroid.testInstrumentationRunnerArguments.fixtureBase64=${Buffer.from(JSON.stringify(fixture)).toString('base64')}`, '--stacktrace',
    ], join(root, 'android'));
    if (performanceMode) {
      const result = JSON.parse(execFileSync(adb, ['exec-out', 'run-as', 'com.household.account', 'cat', 'files/native-performance-result.json'], { encoding: 'utf8' }));
      const validationErrors = [];
      if (result.schemaVersion !== 1) validationErrors.push('Unsupported native performance schema');
      if (result.repetitions !== performanceSamples) validationErrors.push('Native performance repetition count does not match the requested count');
      const expectedMetrics = isolateWebView ? ['android.home.isolated-activity-complete'] :
        ['android.home.activity-reopen-complete', 'android.quick-edit.notification-to-shown',
          'android.quick-edit.notification-to-ready', 'android.quick-edit.save-to-closed', 'android.quick-edit.save-to-server-observed'];
      const performance = evaluatePerformanceBudgets(result.samples, { projects: ['android-emulator'], metrics: expectedMetrics,
        samplesPerMetric: performanceSamples, reportOnly: true, warmupMetrics: expectedMetrics.filter(metric => metric.startsWith('android.quick-edit.')),
        diagnostic: isolateWebView || process.env.PERFORMANCE_DIAGNOSTIC === 'true', ci: Boolean(process.env.CI || process.env.GITHUB_ACTIONS),
        profile: process.env.PERFORMANCE_PROFILE });
      result.status = validationErrors.length > 0 || performance.status === 'fail' ? 'failed' : performance.status;
      result.validationErrors = validationErrors;
      result.performance = performance;
      result.host = { platform: process.platform, osRelease: release(), node: process.version,
        cpu: cpus()[0]?.model, logicalCpus: cpus().length, totalMemoryBytes: totalmem(),
        runnerOs: process.env.RUNNER_OS, runnerArch: process.env.RUNNER_ARCH,
        runnerImage: process.env.ImageOS, runnerImageVersion: process.env.ImageVersion,
        job: process.env.GITHUB_JOB };
      result.dataset = fixture.performanceDataset;
      result.statistics = performance.statistics;
      const nativeResultPath = join(output, isolateWebView ? 'native-performance-isolated-diagnostic-result.json' : 'native-performance-result.json');
      writeFileSync(nativeResultPath, JSON.stringify(result, null, 2), 'utf8');
      const performanceOutput = join(root, 'web/performance-results');
      mkdirSync(performanceOutput, { recursive: true });
      const artifactName = isolateWebView ? 'android-isolated-diagnostic' : 'android';
      writeFileSync(join(performanceOutput, `${artifactName}.json`), JSON.stringify(result, null, 2), 'utf8');
      const markdown = `# Android 핵심 기능 성능 측정\n\n상태: ${result.status}.\n\n${validationErrors.map(error => `- 검증 실패: ${error}`).join('\n')}\n\n${budgetMarkdown(performance)}\n\n${markdownTable(result.statistics)}\n`;
      writeFileSync(join(performanceOutput, `${artifactName}.md`), markdown, 'utf8');
      if (process.env.GITHUB_STEP_SUMMARY) appendFileSync(process.env.GITHUB_STEP_SUMMARY, markdown);
      console.log(`Native Firebase performance samples: ${nativeResultPath}`);
      if (result.status === 'failed') {
        console.error(`Native performance measurement failed:\n${[...validationErrors, ...performance.errors].join('\n')}`);
        process.exitCode = 1;
      }
    } else {
    const startup = JSON.parse(execFileSync(adb, ['exec-out', 'run-as', 'com.household.account', 'cat', 'files/native-startup-e2e-result.json'], { encoding: 'utf8' }));
    assert.equal(startup.platform, 'android');
    assert.equal(startup.sameActivityReloadStartupSamples, 0);
    assert.equal(startup.latestLocalCurrencyBalance, 36890);
    // Observe the actual production logger output. No logging sink or handler is replaced.
    const logText = readLogSince(firebaseLog, logOffset);
    const observations = new Set();
    for (const rawLine of logText.split('\n')) {
      const line = rawLine.replaceAll('\\"', '"');
      if (!line.includes('client.android-app-first-home-complete-paint.v1') || !/"endpoint"\s*:\s*"clientStartup"/.test(line)) continue;
      const elapsed = Number(line.match(/"elapsedMs"\s*:\s*([\d.]+)/)?.[1]);
      if (elapsed !== startup.durationMs) continue;
      const correlation = line.match(/"correlationId"\s*:\s*"([a-z0-9-]+)"/)?.[1];
      assert(correlation, 'Startup log must use a non-identifying correlation ID');
      observations.add(correlation);
    }
    assert.equal(observations.size, 1, 'Actual server logger must record the Native startup sample once');
    writeFileSync(join(output, 'startup-result.json'), JSON.stringify({ ...startup, serverStartupLogSamples: observations.size }), 'utf8');
    }
  }
  if (!performanceMode) {
  const result = JSON.parse(execFileSync(adb, ['exec-out', 'run-as', 'com.household.account', 'cat', 'files/native-firebase-e2e-result.json'], { encoding: 'utf8' }));
  const fixture = JSON.parse(readFileSync(fixturePath, 'utf8'));
  assert.equal(result.householdId, fixture.householdId);
  assert.equal(result.categoryId, fixture.categoryId);
  assert.equal(result.memo, 'Android E2E 메모');
  writeFileSync(resultPath, JSON.stringify(result), 'utf8');
  await run(process.platform === 'win32' ? 'npm.cmd' : 'npm', [
    'run', 'test:e2e:playwright', '--', '--config=playwright.native.config.ts',
  ], join(root, 'web'), { ...process.env, NATIVE_E2E_FIXTURE: fixturePath, NATIVE_E2E_RESULT: resultPath,
    ...(webRuntime ? { NATIVE_E2E_EXISTING_SERVER: 'true' } : {}) });
  }
  } finally { await webRuntime?.stop(); }
}
