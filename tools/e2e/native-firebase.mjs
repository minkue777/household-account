const resultPath = join(output, 'result.json');

function readLogSince(path, offset) {
  const descriptor = openSync(path, 'r');
  try {
    const length = fstatSync(descriptor).size - offset;
    assert(length >= 0, 'Firebase log was truncated during Native E2E');
    const buffer = Buffer.alloc(length);
    let consumed = 0;
    while (consumed < length) {
      const count = readSync(descriptor, buffer, consumed, length - consumed, offset + consumed);
      assert(count > 0, 'Firebase log ended before the observed size');
      consumed += count;
    }
    return buffer.toString('utf8');
  } finally { closeSync(descriptor); }
}

async function jsonRequest(url, options = {}) {
  const response = await fetch(url, { ...options, signal: AbortSignal.timeout(60_000) });
  const text = await response.text();
  assert(response.ok, `Local E2E request failed (${response.status}): ${text}`);
  return text ? JSON.parse(text) : {};
}

async function seed() {
  // Only the fixed demo project on loopback is reachable. Never accept a production project argument.
  await Promise.all([
    jsonRequest(`http://127.0.0.1:9099/emulator/v1/projects/${projectId}/accounts`, { method: 'DELETE' }),
    jsonRequest(`http://127.0.0.1:8080/emulator/v1/projects/${projectId}/databases/(default)/documents`, { method: 'DELETE' }),
  ]);
  const account = await jsonRequest('http://127.0.0.1:9099/identitytoolkit.googleapis.com/v1/accounts:signUp?key=demo-api-key', {
    method: 'POST', headers: { 'content-type': 'application/json' }, body: JSON.stringify({ email, password, returnSecureToken: true }),
  });
  async function command(name, payload, householdId) {
    const commandId = `native-e2e-${randomUUID()}`;
    const response = await jsonRequest(`http://127.0.0.1:5001/${projectId}/asia-northeast3/executeHouseholdCommand`, {
      method: 'POST', headers: { 'content-type': 'application/json', authorization: `Bearer ${account.idToken}` },
      body: JSON.stringify({ data: { contractVersion: 'household-command.v1', commandId, idempotencyKey: commandId,
        ...(householdId ? { householdId } : {}), command: name, payload } }),
    });
    assert.equal(response.result?.contractVersion, 'household-command-response.v1');
    assert.equal(response.result?.result.kind, 'succeeded', `${name}: ${JSON.stringify(response.result)}`);
    return response.result.result.value;
  }
  const household = await command('access.create-household-with-self.v1', { householdName: 'Native E2E', memberName: 'Native E2E' });
  let categoryName = '간식/디저트/커피';
  let categoryId;
  // The ID must be generated by the real server and contain both cases, to catch the original regression.
  for (let attempt = 0; attempt < 5; attempt++) {
    categoryName = `간식/디저트/커피${attempt ? ` ${attempt}` : ''}`;
    ({ categoryId } = await command('category.create.v1', { category: { label: categoryName, color: '#F9A8D4' } }, household.householdId));
    if (/[A-Z]/.test(categoryId) && /[a-z]/.test(categoryId)) break;
  }
  assert(/[A-Z]/.test(categoryId) && /[a-z]/.test(categoryId), 'Server-generated mixed-case category ID is required');
  await command('payment-configuration.register-card.v1', { card: { cardLabel: '국민', cardLastFour: '1234' } }, household.householdId);
  await command('payment-configuration.create-merchant-rule.v1', { rule: {
    merchantKeyword: 'E2E커피점', matchType: 'exact', mapping: { merchant: 'E2E 카페', category: categoryId },
  } }, household.householdId);
  const now = new Date();
  const seoul = new Date(now.getTime() + 9 * 60 * 60 * 1000).toISOString();
  const rawNotification = {
    contractVersion: 'android-raw-notification.v1', observationId: `native-e2e-${randomUUID()}`,
    packageName: 'com.kbcard.cxh.appcard',
    notification: { postedAt: now.toISOString(), title: 'KB국민카드1234 승인', textLines: [
      '12,300원 일시불', `${seoul.slice(5, 7)}/${seoul.slice(8, 10)} ${seoul.slice(11, 16)}`, 'E2E커피점',
    ] },
  };
  const fixture = { projectId, email, password, householdId: household.householdId, memberId: household.memberId,
    categoryId, categoryName, rawNotification, expectedMerchant: 'E2E 카페', expectedAmountInWon: 12300 };
  mkdirSync(output, { recursive: true });
  writeFileSync(fixturePath, JSON.stringify(fixture), 'utf8');
  console.log(`Native Firebase E2E fixture prepared: ${fixturePath}`);
  return fixture;
}

async function run(command, args, cwd = root, env = process.env) {
  await new Promise((resolveRun, reject) => {
    const child = spawn(command, args, { cwd, env, stdio: 'inherit', windowsHide: true, shell: process.platform === 'win32' && /\.(?:bat|cmd)$/.test(command) });
    child.once('error', reject);
    child.once('exit', code => code === 0 ? resolveRun() : reject(new Error(`${command} failed (${code})`)));
  });
}

const mode = process.argv[2] ?? 'run';
assert(['run', 'seed', 'verify'].includes(mode), 'Usage: node tools/e2e/native-firebase.mjs [run|seed|verify]');
if (mode === 'seed') await seed();
else {
  const adb = process.env.ANDROID_HOME || process.env.ANDROID_SDK_ROOT
    ? join(process.env.ANDROID_HOME ?? process.env.ANDROID_SDK_ROOT, 'platform-tools', process.platform === 'win32' ? 'adb.exe' : 'adb') : 'adb';
  let webRuntime;
  const firebaseLog = join(root, 'firebase-debug.log');
  let logOffset = 0;
  try {
  if (mode === 'run') {
    const fixture = await seed();
    webRuntime = await startNativeWebRuntime(root, output, adb);
    logOffset = existsSync(firebaseLog) ? statSync(firebaseLog).size : 0;
    await run(process.platform === 'win32' ? 'gradlew.bat' : './gradlew', [
      'connectedDebugAndroidTest', '-PfirebaseE2e=true', '-PfirebaseWebE2e=true',
      // AGP normally uninstalls both APKs before Gradle returns, deleting private result files.
      // Its supported stable option preserves the E2E installation for the reads below.
      '-Pandroid.injected.androidTest.leaveApksInstalledAfterRun=true',
      `-PWEB_APP_URL=${webRuntime.origin}/`, '-PWEB_ENVIRONMENT_VERSION=emulator-e2e-v1',
      `-Pandroid.testInstrumentationRunnerArguments.webOrigin=${webRuntime.origin}`,
      `-Pandroid.testInstrumentationRunnerArguments.fixtureBase64=${Buffer.from(JSON.stringify(fixture)).toString('base64')}`, '--stacktrace',
    ], join(root, 'android'));
    const startup = JSON.parse(execFileSync(adb, ['exec-out', 'run-as', 'com.household.account', 'cat', 'files/native-startup-e2e-result.json'], { encoding: 'utf8' }));
    assert.equal(startup.platform, 'android');
    assert.equal(startup.sameActivityReloadStartupSamples, 0);
    assert.equal(startup.latestLocalCurrencyBalance, 36890);
    // Observe the actual production logger output. No logging sink or handler is replaced.
    const logText = readLogSince(firebaseLog, logOffset);
    const observations = new Set();
    for (const rawLine of logText.split('\n')) {
      const line = rawLine.replaceAll('\\"', '"');
      if (!line.includes('client.android-app-first-home-complete-paint.v1') || !/"endpoint"\s*:\s*"clientStartup"/.test(line)) continue;
      const elapsed = Number(line.match(/"elapsedMs"\s*:\s*([\d.]+)/)?.[1]);
      if (elapsed !== startup.durationMs) continue;
      const correlation = line.match(/"correlationId"\s*:\s*"([a-z0-9-]+)"/)?.[1];
      assert(correlation, 'Startup log must use a non-identifying correlation ID');
      observations.add(correlation);
    }
    assert.equal(observations.size, 1, 'Actual server logger must record the Native startup sample once');
    writeFileSync(join(output, 'startup-result.json'), JSON.stringify({ ...startup, serverStartupLogSamples: observations.size }), 'utf8');
  }
  const result = JSON.parse(execFileSync(adb, ['exec-out', 'run-as', 'com.household.account', 'cat', 'files/native-firebase-e2e-result.json'], { encoding: 'utf8' }));
  const fixture = JSON.parse(readFileSync(fixturePath, 'utf8'));
  assert.equal(result.householdId, fixture.householdId);
  assert.equal(result.categoryId, fixture.categoryId);
  assert.equal(result.memo, 'Android E2E 메모');
  writeFileSync(resultPath, JSON.stringify(result), 'utf8');
  await run(process.platform === 'win32' ? 'npm.cmd' : 'npm', [
    'run', 'test:e2e:playwright', '--', '--config=playwright.native.config.ts',
  ], join(root, 'web'), { ...process.env, NATIVE_E2E_FIXTURE: fixturePath, NATIVE_E2E_RESULT: resultPath,
    ...(webRuntime ? { NATIVE_E2E_EXISTING_SERVER: 'true' } : {}) });
  } finally { await webRuntime?.stop(); }
}
